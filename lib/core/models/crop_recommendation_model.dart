import 'weather_model.dart';

/// Soil and farm parameters provided by the farmer for crop recommendation
class CropRecommendationInput {
  final String soilType;
  final String season;
  final String waterSource;
  final String landArea;
  final String previousCrop;
  final bool hasMeasuredSoilTest;
  final double? nitrogen; // kg/ha
  final double? phosphorus; // kg/ha
  final double? potassium; // kg/ha
  final double? ph; // pH scale (0-14)
  final String location;

  const CropRecommendationInput({
    required this.soilType,
    required this.season,
    required this.waterSource,
    required this.landArea,
    required this.previousCrop,
    required this.hasMeasuredSoilTest,
    this.nitrogen,
    this.phosphorus,
    this.potassium,
    this.ph,
    required this.location,
  });

  Map<String, dynamic> toMap() => {
        'soilType': soilType,
        'season': season,
        'waterSource': waterSource,
        'landArea': landArea,
        'previousCrop': previousCrop,
        'hasMeasuredSoilTest': hasMeasuredSoilTest,
        'nitrogen': nitrogen,
        'phosphorus': phosphorus,
        'potassium': potassium,
        'ph': ph,
        'location': location,
      };
}

/// A specific crop suggestion generated by AI
class CropRecommendationItem {
  final String cropName;
  final int matchScore; // 0 to 100%
  final String expectedYield;
  final String expectedProfit;
  final String durationDays;
  final String marketDemand;
  final String growingConditions;
  final List<String> precautions;
  final String whyRecommended;

  const CropRecommendationItem({
    required this.cropName,
    required this.matchScore,
    required this.expectedYield,
    required this.expectedProfit,
    required this.durationDays,
    required this.marketDemand,
    required this.growingConditions,
    required this.precautions,
    required this.whyRecommended,
  });

  factory CropRecommendationItem.fromMap(Map<String, dynamic> map) {
    return CropRecommendationItem(
      cropName: map['cropName'] as String? ?? 'Recommended Crop',
      matchScore: (map['matchScore'] as num?)?.toInt() ?? 90,
      expectedYield: map['expectedYield'] as String? ?? '12 - 16 Quintals / Acre',
      expectedProfit: map['expectedProfit'] as String? ?? '₹50,000 - ₹70,000 / Acre',
      durationDays: map['durationDays'] as String? ?? '120 - 140 Days',
      marketDemand: map['marketDemand'] as String? ?? 'High Demand',
      growingConditions: map['growingConditions'] as String? ??
          'Optimum growth in well-drained fertile soil with regular irrigation intervals.',
      precautions: (map['precautions'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          ['Ensure weed-free field during first 45 days'],
      whyRecommended: map['whyRecommended'] as String? ??
          'Well matched to soil texture, seasonal climate, and water availability.',
    );
  }

  Map<String, dynamic> toMap() => {
        'cropName': cropName,
        'matchScore': matchScore,
        'expectedYield': expectedYield,
        'expectedProfit': expectedProfit,
        'durationDays': durationDays,
        'marketDemand': marketDemand,
        'growingConditions': growingConditions,
        'precautions': precautions,
        'whyRecommended': whyRecommended,
      };
}

/// Overall recommendation outcome container
class CropRecommendationResult {
  final String id;
  final CropRecommendationInput input;
  final FarmWeather? weather;
  final List<CropRecommendationItem> recommendations;
  final bool isMeasuredSoil;
  final String advisoryNotice;
  final DateTime createdAt;
  final bool isDemoData; // Rule 10: Clearly marks offline demo baseline vs real AI

  const CropRecommendationResult({
    required this.id,
    required this.input,
    this.weather,
    required this.recommendations,
    required this.isMeasuredSoil,
    required this.advisoryNotice,
    required this.createdAt,
    this.isDemoData = false,
  });

  String get soilMeasurementStatus => isMeasuredSoil
      ? 'Measured Soil Lab Data (Tested)'
      : 'Regional Agro-Climatic Estimate (Unmeasured)';
}
